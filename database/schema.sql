-- Drop tables if they exist (in reverse order of foreign keys)
BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE PAYMENTS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE BOOKINGS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE TRAINS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

BEGIN
   EXECUTE IMMEDIATE 'DROP TABLE USERS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

-- 1. USERS TABLE
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20),
    ROLE VARCHAR2(20) DEFAULT 'USER' NOT NULL
);

-- 2. TRAINS TABLE
CREATE TABLE TRAINS (
    TRAIN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TRAIN_NAME VARCHAR2(100) NOT NULL,
    TRAIN_NUMBER VARCHAR2(20) NOT NULL UNIQUE,
    SOURCE_STATION VARCHAR2(100) NOT NULL,
    DESTINATION_STATION VARCHAR2(100) NOT NULL,
    DEPARTURE_TIME VARCHAR2(20) DEFAULT '08:00 AM',
    ARRIVAL_TIME VARCHAR2(20) DEFAULT '08:00 PM',
    FARE NUMBER(10, 2) NOT NULL,
    TOTAL_SEATS NUMBER(5) DEFAULT 100 NOT NULL,
    AVAILABLE_SEATS NUMBER(5) DEFAULT 100 NOT NULL,
    TRAIN_TYPE VARCHAR2(50) DEFAULT 'Express'
);

-- 3. BOOKINGS TABLE
CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PNR VARCHAR2(20) NOT NULL UNIQUE,
    PASSENGER_NAME VARCHAR2(100) NOT NULL,
    JOURNEY_DATE DATE NOT NULL,
    COACH VARCHAR2(10) DEFAULT 'B1' NOT NULL,
    SEAT_NUMBER VARCHAR2(20) NOT NULL,
    PASSENGERS NUMBER(3) DEFAULT 1 NOT NULL,
    TOTAL_AMOUNT NUMBER(10, 2) NOT NULL,
    BOOKING_STATUS VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
    USER_ID NUMBER,
    TRAIN_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BOOKING_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE SET NULL,
    CONSTRAINT FK_BOOKING_TRAIN FOREIGN KEY (TRAIN_ID) REFERENCES TRAINS(TRAIN_ID) ON DELETE CASCADE
);

-- 4. PAYMENTS TABLE
CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOKING_ID NUMBER NOT NULL,
    AMOUNT NUMBER(10, 2) NOT NULL,
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'SUCCESS' NOT NULL,
    PAYMENT_METHOD VARCHAR2(50) DEFAULT 'UPI',
    TRANSACTION_ID VARCHAR2(50) NOT NULL UNIQUE,
    PAYMENT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PAYMENT_BOOKING FOREIGN KEY (BOOKING_ID) REFERENCES BOOKINGS(BOOKING_ID) ON DELETE CASCADE
);

-- Create helpful indexes for performance
CREATE INDEX IDX_TRAINS_ROUTE ON TRAINS(SOURCE_STATION, DESTINATION_STATION);
CREATE INDEX IDX_BOOKINGS_PNR ON BOOKINGS(PNR);
CREATE INDEX IDX_BOOKINGS_USER ON BOOKINGS(USER_ID);

COMMIT;
